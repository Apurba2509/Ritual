/** Resolve a habit's icon, upgrading legacy emoji. */
export function habitIconKey(raw: { icon?: unknown; emoji?: unknown }): string {
  if (typeof raw.icon === 'string' && raw.icon) return raw.icon;
  if (typeof raw.emoji === 'string') return EMOJI_TO_ICON[raw.emoji] ?? DEFAULT_HABIT_ICON;
  return DEFAULT_HABIT_ICON;
}

