/**
 * Generates src/ui/icons.ts — the curated set of Phosphor icons Ritual uses.
 * Each icon is imported from its own module so the bundle only carries what's listed here
 * (importing the package root would pull in all ~1,500 icons × 6 weights).
 *
 *   node scripts/gen-icons.cjs
 */
const fs = require('fs');
const path = require('path');

const UI = `
  alarm archive arrow-clockwise arrow-counter-clockwise arrow-left arrow-right arrow-up-right arrows-clockwise at
  bell bell-slash calendar-blank calendar-check camera caret-down caret-left caret-right caret-up chart-bar
  chart-line-up chat-circle chat-teardrop-text check check-circle clock clock-countdown cloud cloud-check
  cloud-slash compass confetti copy crown crosshair device-mobile dots-three download-simple envelope-simple
  export eye eye-slash fire flag gear-six github-logo globe-simple hand-waving hands-clapping hexagon house
  image info infinity key lightning link list-checks lock-simple magic-wand magnifying-glass medal microphone
  minus moon paper-plane-tilt pause pencil-simple play plus plus-circle prohibit quotes ranking repeat
  rocket-launch seal-check share-network shield-check sign-in sign-out sliders-horizontal smiley smiley-blank
  smiley-meh smiley-sad smiley-wink sparkle squares-four star sun-horizon target thumbs-up timer trash
  trend-down trend-up trophy upload-simple user user-circle user-plus users-three warning x
  arrow-u-up-left arrow-down-right calendar-x flag-banner stack-minus hand-palm battery-warning
  battery-charging shield-warning hourglass hourglass-high ladder stairs path lock-key key tray
`;

const HABITS = `
  drop bed moon-stars pill tooth orange-slice carrot bowl-food fork-knife cooking-pot coffee cigarette-slash
  heartbeat heart hand-soap shower sun person-simple-run person-simple-walk person-simple-bike person-simple-swim
  person-simple-tai-chi footprints barbell bicycle sneaker soccer-ball basketball mountains brain flower-lotus
  leaf plant potted-plant tree wind hand-heart notebook pencil-line feather book-open-text books
  graduation-cap translate lightbulb flask calculator music-notes guitar piano-keys headphones pen-nib atom code
  terminal-window git-commit puzzle-piece laptop briefcase hourglass-medium kanban check-square
  dog cat paw-print phone chats-circle gift wallet piggy-bank coins receipt shopping-cart paint-brush palette
  film-slate game-controller device-mobile-slash car snowflake beer-bottle bookmark scroll broom
`;

const names = [...new Set(`${UI} ${HABITS}`.split(/\s+/).filter(Boolean))].sort();
const pascal = (k) =>
  k
    .split('-')
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('');
const root = path.join(__dirname, '..');
const missing = names.filter(
  (k) => !fs.existsSync(path.join(root, 'node_modules/phosphor-react-native/src/icons', `${pascal(k)}.tsx`)),
);
if (missing.length) throw new Error(`Unknown Phosphor icons: ${missing.join(', ')}`);

const out = [
  '/* Generated by scripts/gen-icons.cjs — edit the list there, then run `node scripts/gen-icons.cjs`. */',
  "import type { Icon } from 'phosphor-react-native';",
  ...names.map((k) => `import { ${pascal(k)}Icon } from 'phosphor-react-native/src/icons/${pascal(k)}';`),
  '',
  'export const ICONS = {',
  ...names.map((k) => `  '${k}': ${pascal(k)}Icon,`),
  '} satisfies Record<string, Icon>;',
  '',
  'export type IconName = keyof typeof ICONS;',
  '',
  "export const isIconName = (v: unknown): v is IconName => typeof v === 'string' && v in ICONS;",
  '',
].join('\n');
fs.writeFileSync(path.join(root, 'src/ui/icons.ts'), out);
console.log(`${names.length} icons → src/ui/icons.ts`);
